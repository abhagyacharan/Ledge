import { sql } from "drizzle-orm";
import {
  check,
  date,
  foreignKey,
  index,
  pgTable,
  smallint,
  text,
  time,
  timestamp,
  unique,
  uuid,
  type AnyPgColumn,
} from "drizzle-orm/pg-core";
import { createdAt, id, tsvector, updatedAt } from "./_columns";
import { user } from "./auth";
import { lists } from "./lists";
import { sections } from "./sections";

export const TASK_STATUSES = ["open", "done"] as const;
export type TaskStatus = (typeof TASK_STATUSES)[number];

export const RECURRENCE_MODES = ["fixed", "after_completion"] as const;
export type RecurrenceMode = (typeof RECURRENCE_MODES)[number];

export const tasks = pgTable(
  "tasks",
  {
    id: id(),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    listId: uuid("list_id").notNull(),
    /** Null means "no section". Deleting a section sets this to null. */
    sectionId: uuid("section_id").references(() => sections.id, { onDelete: "set null" }),
    /** Subtasks point at their parent. One level only: enforced by a trigger. */
    parentId: uuid("parent_id").references((): AnyPgColumn => tasks.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    notes: text("notes"),
    status: text("status", { enum: TASK_STATUSES }).notNull().default("open"),
    /** 0 none, 1 low, 2 medium, 3 high. */
    priority: smallint("priority").notNull().default(0),
    /** Floating date: no time zone, read in the user's timezone (CLAUDE.md §6.3). */
    dueDate: date("due_date", { mode: "string" }),
    /** Floating time of day, only meaningful together with `due_date`. */
    dueTime: time("due_time"),
    /** RRULE subset (Phase 10). */
    recurrenceRule: text("recurrence_rule"),
    recurrenceMode: text("recurrence_mode", { enum: RECURRENCE_MODES }).notNull().default("fixed"),
    /** For a completed snapshot of a recurring task: the task it came from. */
    recurrenceOriginId: uuid("recurrence_origin_id").references((): AnyPgColumn => tasks.id, {
      onDelete: "set null",
    }),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    /** Fractional-index string (CLAUDE.md §3). */
    position: text("position").notNull(),
    /** Soft delete: set means the task is in Trash. */
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
    /** Generated by Postgres from title and notes. Never written by the app. */
    search: tsvector("search").generatedAlwaysAs(
      sql`to_tsvector('english', coalesce(title, '') || ' ' || coalesce(notes, ''))`,
    ),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    // Composite FK: the list must belong to the same user as the task.
    foreignKey({
      name: "tasks_list_owner_fk",
      columns: [t.listId, t.userId],
      foreignColumns: [lists.id, lists.userId],
    }).onDelete("cascade"),
    unique("tasks_id_user_id_key").on(t.id, t.userId),
    index("tasks_user_list_position_idx").on(t.userId, t.listId, t.position),
    index("tasks_user_due_date_open_idx")
      .on(t.userId, t.dueDate)
      .where(sql`${t.deletedAt} is null and ${t.status} = 'open'`),
    index("tasks_search_idx").using("gin", t.search),
    index("tasks_user_completed_at_idx").on(t.userId, t.completedAt),
    index("tasks_parent_idx").on(t.parentId),
    check("tasks_title_check", sql`char_length(${t.title}) between 1 and 500`),
    check("tasks_status_check", sql`${t.status} in ('open', 'done')`),
    check("tasks_priority_check", sql`${t.priority} between 0 and 3`),
    check("tasks_recurrence_mode_check", sql`${t.recurrenceMode} in ('fixed', 'after_completion')`),
    check("tasks_due_time_needs_date_check", sql`${t.dueTime} is null or ${t.dueDate} is not null`),
    // Completing sets completed_at; reopening clears it. They must always agree.
    check(
      "tasks_completed_at_matches_status_check",
      sql`(${t.status} = 'done') = (${t.completedAt} is not null)`,
    ),
    check("tasks_not_own_parent_check", sql`${t.parentId} is null or ${t.parentId} <> ${t.id}`),
  ],
);

export type Task = typeof tasks.$inferSelect;
export type NewTask = typeof tasks.$inferInsert;
